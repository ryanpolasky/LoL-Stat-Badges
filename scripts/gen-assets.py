import base64, io, json, os
from fontTools.ttLib import TTFont
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ASSETS = os.path.join(ROOT, "assets")

icons = {}
for f in sorted(os.listdir(ASSETS)):
    if f.endswith(".png"):
        img = Image.open(os.path.join(ASSETS, f)).convert("RGBA")
        img.thumbnail((56, 56), Image.LANCZOS)
        buf = io.BytesIO()
        img.save(buf, "PNG", optimize=True)
        icons[f[:-4]] = base64.b64encode(buf.getvalue()).decode()

font = TTFont(os.path.join(ASSETS, "fonts", "Verdana.ttf"))
upem = font["head"].unitsPerEm
hmtx = font["hmtx"]
widths = {
    cp: round(hmtx[name][0] / upem, 4)
    for cp, name in font.getBestCmap().items()
    if 32 <= cp < 0x3000
}

with open(os.path.join(ROOT, "src", "generated.ts"), "w") as out:
    out.write("// generated by scripts/gen-assets.py\n")
    out.write(f"export const ICONS: Record<string, string> = {json.dumps(icons, indent=2)};\n\n")
    out.write(f"export const VERDANA_WIDTHS: Record<number, number> = {json.dumps(widths, separators=(',', ':'))};\n")
